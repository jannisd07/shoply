/// Shared test recipes for the browse tests (Konzept 13 §3.2 examples).
final browseNow = DateTime(2026, 11, 8, 10);

Recipe browseRecipe(
  String id, {
  String? name,
  int prep = 10,
  int cook = 15,
  double rating = 4.5,
  int ratings = 10,
  int views = 0,
  List<String> labels = const [],
  List<String> ingredients = const ['Zwiebel'],
  String author = 'a1',
  String authorName = 'Mara Köhler',
  int ageDays = 10,
  String language = 'de',
  String description = '',
}) => Recipe(
  id: id,
  name: name ?? 'Rezept $id',
  description: description,
  imageUrl: '',
  prepTimeMinutes: prep,
  cookTimeMinutes: cook,
  defaultServings: 2,
  ingredients: [
    for (final i in ingredients) Ingredient(name: i, amount: 1, unit: ''),
  ],
  instructions: const ['Kochen'],
  authorId: author,
  authorName: authorName,
  createdAt: browseNow.subtract(Duration(days: ageDays)),
  averageRating: rating,
  ratingCount: ratings,
  viewCount: views,
  labels: labels,
  language: language,
);

