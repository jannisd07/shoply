/// App start (Kap. 20 §2.2). Before `runApp` only what the first frame
/// needs, all of it local: orientation, the SharedPreferences plist (read
/// once, every later `getInstance()` reuses it), the stored Supabase session
/// and the cached kill switches. Everything else runs in [_startup], after
/// the first frame. Categorisation, Claude, photos, voice, Health and
/// location start on first use, and no permission prompt appears at start.
///
/// Timeline: `boot:*` before the first frame, `post:*` after it (DevTools
/// Performance, `flutter run --profile --trace-startup`).
Future<void> main() async {
  final boot = Stopwatch()..start();
  Timeline.instantSync('boot:start');
  WidgetsFlutterBinding.ensureInitialized();

  final prefsLoad = _span('boot:prefs', SharedPreferences.getInstance);
  await Future.wait<Object?>([
    _span(
      'boot:orientation',
      () => SystemChrome.setPreferredOrientations([
        DeviceOrientation.portraitUp,
        DeviceOrientation.portraitDown,
      ]),
    ),
    prefsLoad,
    _span('boot:supabase', SupabaseService.initialize),
    _span('boot:flags', AppFlagsService.instance.loadCache),
  ]);
  final prefs = await prefsLoad;

  final container = ProviderContainer(
    overrides: [
      // Already loaded, so the calorie diary has its numbers in frame 1.
      sharedPreferencesProvider.overrideWith((ref) => prefs),
    ],
  );

  runApp(
    UncontrolledProviderScope(container: container, child: const AvoApp()),
  );
  Timeline.instantSync('boot:runApp');
  if (!kReleaseMode) {
    debugPrint('🔵 [BOOT] ${boot.elapsedMilliseconds} ms before runApp');
    reportStartupFrames();
  }

  unawaited(_startup(isMobile: Platform.isIOS || Platform.isAndroid).run());
}

Future<T> _span<T>(String name, Future<T> Function() work) async {
  final span = TimelineTask()..start(name);
  try {
    return await work();
  } finally {
    span.finish();
  }
}

/// The plan from [appStartupPhases] with the real services. A phase starts
/// at its offset even if an earlier one is still busy, and a failing task
/// never stops the others.
StartupScheduler _startup({required bool isMobile}) {
  // The reminders schedule local notifications, so they wait for the plugin
  // (initialize() is shared and runs once).
  Future<void> notificationsReady() => NotificationService.instance.initialize();

  return StartupScheduler(
    appStartupPhases(
      AppStartupWork(
        auth: () => _listenToAuthChanges(isMobile),
        connectivity: () => ConnectivityService.instance.initialize(),
        notifications: notificationsReady,
        firebase: _startFirebase,
        subscription: () => SubscriptionService.instance.initialize(),
        recipeCache: () => OfflineCacheService.instance.warmRecipes(),
        appFlags: () => AppFlagsService.instance.refresh(),
        reminders: () async {
          await notificationsReady();
          await MascotNotificationService.instance.rearmAfterLaunch();
        },
        appReview: () => AppReviewService.instance.trackAppOpen(),
      ),
      isMobile: isMobile,
    ),
  );
}

/// Firebase core, Analytics, then FCM (needs Firebase). Skipped (loudly)
/// when lib/firebase_options.dart is still the placeholder from
/// firebase_options.example.dart; the app runs without push then.
Future<void> _startFirebase() async {
  final opts = DefaultFirebaseOptions.currentPlatform;
  if (opts.apiKey.startsWith('YOUR_')) {
    debugPrint(
      '❌ [FIREBASE] lib/firebase_options.dart is the placeholder - '
      'Firebase, Analytics and FCM push are DISABLED in this build. '
      'Generate it with flutterfire configure.',
    );
    return;
  }
  await Firebase.initializeApp(options: opts);
  try {
    await AnalyticsService.instance.initialize();
  } catch (e) {
    debugPrint('⚠️ [FIREBASE] Analytics initialization failed: $e');
  }
  await FCMService.instance.initialize();
}

/// Auth side effects: widget credentials, FCM token and reminders.
/// Registered after the first frame; the auth stream replays its latest
/// event, so the restored session still arrives.
void _listenToAuthChanges(bool isMobile) {
  Supabase.instance.client.auth.onAuthStateChange.listen((data) async {
    final event = data.event;
    debugPrint('🔐 [AUTH] State changed: $event');

    // Keep the widget's cached Supabase credentials fresh. The widget
    // process syncs toggles / quick-adds via direct REST calls with this
    // cached token, so it must follow every sign-in and token refresh. This
    // listener is the only auth listener for it; Home has none of its own
    // and only pushes the current session once when it opens.
    if (event == AuthChangeEvent.initialSession ||
        event == AuthChangeEvent.signedIn ||
        event == AuthChangeEvent.tokenRefreshed) {
      unawaited(WidgetService.syncCredentialsFromSession(session: data.session));
    }

    if (event == AuthChangeEvent.signedOut) {
      // The offline cache and learned category choices are not keyed by
      // user — drop them so the next account never sees this one's data.
      UserCategoryPreferences.instance.clearCache();
      unawaited(OfflineCacheService.instance.clearCache());
      AccountSessionCaches.clearForSignOut();
    }

    if (!isMobile) return;

    try {
      if (event == AuthChangeEvent.signedIn) {
        // Sync the master notification switch first: saveTokenForCurrentUser
        // respects it, so a user who disabled notifications on another
        // device doesn't get their FCM token resurrected here.
        await NotificationPreferencesService.instance.syncFromRemote();
        await FCMService.instance.saveTokenForCurrentUser();
        await MascotNotificationService.instance
            .rearmRestockReminder(force: true);
        await MascotNotificationService.instance
            .rearmDinnerIdeasReminder(force: true);
      }

      if (event == AuthChangeEvent.signedOut) {
        // Clears the scheduled restock reminder (no user = nothing due).
        await MascotNotificationService.instance
            .rearmRestockReminder(force: true);
        await MascotNotificationService.instance
            .rearmDinnerIdeasReminder(force: true);
        // Drop all widget data + cached credentials from the App Group —
        // without this, home-screen widgets keep showing the signed-out
        // account's list contents (and Siri keeps suggesting its lists)
        // indefinitely.
        await WidgetService.clearWidget();
      }
    } catch (e) {
      debugPrint('⚠️ [AUTH] Auth side effect failed: $e');
    }
  });
}
